/** Read-only SQL introspection. SQL migrations, not ORM generation, own constraints. */
import type { Pool } from "pg";
export interface ColumnShape {
  name: string;
  type: string;
  nullable: boolean;
  default: string | null;
  generated: boolean;
  primary: boolean;
}
export interface TableShape {
  name: string;
  columns: ColumnShape[];
}
export interface SchemaShape {
  enums: { name: string; values: string[] }[];
  tables: TableShape[];
}
export async function inspectSchema(pool: Pool): Promise<SchemaShape> {
  const enums = (
    await pool.query(
      "SELECT t.typname AS name,json_agg(e.enumlabel ORDER BY e.enumsortorder) AS values FROM pg_type t JOIN pg_enum e ON e.enumtypid=t.oid JOIN pg_namespace n ON n.oid=t.typnamespace WHERE n.nspname='memeradar' GROUP BY t.typname ORDER BY t.typname",
    )
  ).rows;
  const rows = (
    await pool.query(`SELECT c.relname AS table,a.attname AS name,t.typname AS type,NOT a.attnotnull AS nullable,
 pg_get_expr(d.adbin,d.adrelid) AS default,a.attgenerated<>'' AS generated,
 EXISTS(SELECT 1 FROM pg_constraint p WHERE p.conrelid=c.oid AND p.contype='p' AND a.attnum=ANY(p.conkey)) AS primary
 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace JOIN pg_attribute a ON a.attrelid=c.oid AND a.attnum>0 AND NOT a.attisdropped JOIN pg_type t ON t.oid=a.atttypid
 LEFT JOIN pg_attrdef d ON d.adrelid=c.oid AND d.adnum=a.attnum WHERE n.nspname='memeradar' AND c.relkind='r' ORDER BY c.relname,a.attnum`)
  ).rows;
  const tables: TableShape[] = [];
  for (const row of rows) {
    let table = tables.at(-1);
    if (!table || table.name !== row.table) {
      table = { name: row.table, columns: [] };
      tables.push(table);
    }
    const { table: _, ...column } = row;
    table.columns.push(column);
  }
  return { enums, tables };
}
const camel = (value: string) =>
  value.replace(/_([a-z])/g, (_, letter: string) => letter.toUpperCase());
export function renderSchema(shape: SchemaShape): string {
  const lines = [
    `// Generated by npm run db:schema -- --write from a migrated scratch database.`,
    `// SQL is authoritative for FK/check/index/RLS/trigger definitions; never use drizzle push.`,
    `import {sql} from 'drizzle-orm';`,
    `import {pgSchema,text,uuid,boolean,integer,bigint,numeric,jsonb,timestamp,customType} from 'drizzle-orm/pg-core';`,
    `export const memeradar=pgSchema('memeradar');`,
    `const exact=(type:string)=>customType<{data:string;driverData:string}>({dataType:()=>type,fromDriver:value=>String(value),toDriver:value=>value});`,
  ];
  for (const name of [
    "exact_nonnegative",
    "fraction",
    "percentage",
    "raw_quantity",
    "http_url",
  ])
    lines.push(`const ${camel(name)}=exact('"memeradar"."${name}"');`);
  lines.push(`const bit64=exact('bit(64)');`);
  for (const item of shape.enums)
    lines.push(
      `export const ${camel(item.name)}=memeradar.enum(${JSON.stringify(item.name)},${JSON.stringify(item.values)});`,
    );
  const types: Record<string, string> = {
    uuid: "uuid",
    text: "text",
    bool: "boolean",
    int4: "integer",
    int8: "bigint",
    numeric: "numeric",
    jsonb: "jsonb",
    timestamptz: "timestamp",
    bit: "bit64",
    _text: "text",
  };
  for (const table of shape.tables) {
    lines.push(
      `export const ${camel(table.name)}=memeradar.table(${JSON.stringify(table.name)},{`,
    );
    for (const column of table.columns) {
      const type =
        types[column.type] ??
        (shape.enums.some((e) => e.name === column.type) ||
        [
          "exact_nonnegative",
          "fraction",
          "percentage",
          "raw_quantity",
          "http_url",
        ].includes(column.type)
          ? camel(column.type)
          : null);
      if (!type) throw new Error(`Unsupported SQL type ${column.type}`);
      const options =
        column.type === "timestamptz"
          ? ",{withTimezone:true,mode:'date'}"
          : column.type === "int8"
            ? ",{mode:'bigint'}"
            : "";
      let expression = `${type}(${JSON.stringify(column.name)}${options})`;
      if (column.type === "_text") expression += ".array()";
      if (column.generated)
        expression += `.generatedAlwaysAs(sql.raw(${JSON.stringify(column.default)}))`;
      else if (column.default !== null)
        expression += `.default(sql.raw(${JSON.stringify(column.default)}))`;
      if (column.primary) expression += ".primaryKey()";
      else if (!column.nullable) expression += ".notNull()";
      lines.push(`${camel(column.name)}:${expression},`);
    }
    lines.push("});");
  }
  lines.push(
    `export const schemaTables={${shape.tables.map((table) => camel(table.name)).join(",")}};`,
  );
  return lines.join("\n") + "\n";
}
